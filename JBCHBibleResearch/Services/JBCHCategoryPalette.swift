//  보이지 않음. 적극적으로 사용할 수 있도록. 설정에서의 다양한 색상의 아이콘 /
//  통합검색의 분류별 아이콘(성경, 개요, 메모, 개인묵상, 말씀요약, 연구문서)."
//  `AccentColor.colorset`(퍼스널 컬러 — 서재 금박/연한 금박)는 이미 반영됐지만,
//  설정 카테고리 아이콘·통합검색 분류 아이콘처럼 "같은 화면 안에서 서로 다른
//  항목을 색으로 구분"해야 하는 자리는 액센트 색 하나로는 부족해 지금까지
//  iOS 기본 색(파랑/분홍/청록/보라/인디고/갈색 등)을 그대로 썼다 — 그래서
//  이 브랜드 색들이 화면에서 잘 안 보인다는 사용자 지적이 정확하다.
//
//  이 파일은 기존 팔레트(서재 금박/밤빛 남색/가죽 표지 — 각각 이미 다른
//  파일에 상수로 있던 것을 이 구분색 용도로 재사용)에, 같은 톤·채도로 새로
//  고른 색 셋(서고 청람/와인 적갈/서가 슬레이트)을 더해 "6색 구분 팔레트"를
//  한 곳에 모은다 — `SettingsView.SettingsCategoryRow`/`SearchView`의 분류
//  아이콘이 함께 참조해, 두 화면에서 같은 이름의 색이 항상 같은 hex를
//  가리키게 한다(따로 하드코딩하면 나중에 어긋날 수 있음).
//
//  ⚠️ [색 선택 근거] 새 세 색은 정확한 톤(hex)이 정해진 공식 문서가 없는
//  "제품 취향" 영역이라 — `VerseAnnotationRenderer.phraseNoteTextColor`/
//  `hanjaWordTextColor`(같은 성격의 임의 선택, 그 파일 주석 참고)와 동일한
//  원칙으로, 기존 다섯 색과 같은 채도대의 "고서·가죽·서고" 톤을 새로
//  골랐다 — 필요하면 이 파일의 hex 값만 바꾸면 된다. 실제 화면에 적용하기
//  전 사용자에게 제시해 승인받은 값 그대로다(2026-09-04 대화 — "05~07 반영
//  하도록").
//
//  ⚠️ [의도적으로 포함하지 않은 것] 상태 배지(완료=초록/대기=주황/실패=빨강,
//  `DocumentsHomeView.statusBadge`)와 참조 일치·태그 배지(초록/파랑)는 이
//  "구분색" 팔레트가 아니라 전 세계 공통 상태 신호/기능적 색이라 이 파일이
//  다루지 않는다 — 그 파일들에서 직접 채도만 낮춰 처리한다(별도 커밋).
//

import SwiftUI

/// 설정 카테고리 아이콘·통합검색 분류 아이콘이 함께 쓰는 "구분용" 6색.
/// 각 항목에 어느 색을 배정할지는 화면(SettingsView/SearchView)의 몫이다 —
/// 이 enum은 색 자체의 정의만 갖는다.
enum JBCHCategoryPalette {
    /// 밤빛 남색 — `AccentColor` 다크모드 그러데이션과 같은 색(앱 아이콘 배경).
    /// 성경 본문/번역본처럼 "본문과 직접 관련된" 항목에 배정한다.
    static let navy = Color(hex: "#182644") ?? .indigo

    /// 서재 금박 — 퍼스널 컬러(`AccentColor.colorset`)와 같은 색. 이미 선택/
    /// 강조를 의미하는 색이라, 구분색으로 쓸 때도 "사용자가 직접 다루는"
    /// 항목(모양 설정, 메모)에 한정해 배정한다.
    static let gold = Color(hex: "#B8863C") ?? .orange

    /// 가죽 표지 — `VerseAnnotationRenderer`가 쓰는 것과 별개로, 여기서는
    /// 절제된 2차 구분색으로 쓴다.
    static let wood = Color(hex: "#5A3826") ?? .brown

    /// 서고 청람 — [2026-09-04 신규] 고서·서고 분위기의 차분한 청록.
    static let slateTeal = Color(hex: "#4F6D6A") ?? .teal

    /// [2026-09-11 신규] 서고 청람을 흰색과 20% 섞은 변형 — "밤빛 서재"
    /// 다크 배경(#182644) 위에 원래 서고 청람을 그대로 쓰면 WCAG 대비가
    /// 2.66:1로 UI 구성요소 권장 최소치(3:1)에 못 미친다(공식 계산 확인).
    /// 이 변형은 같은 배경 위에서 대비 4.09:1이 나온다. 어두운 배경일 때만
    /// `PhoneTabView.swift`의 `applyThemedTabBarAppearance`가 이 값을 쓴다.
    static let slateTealOnDark = Color(hex: "#728A88") ?? .teal

    /// [2026-09-11 신규] 밤빛 남색을 흰색과 40% 섞은 변형 — 밤빛 남색
    /// 자체가 원래 아주 어두운 색(#182644)이라, 시스템이 다크 모드일 때
    /// (설정 화면 등 성경 조회 테마와 무관한 시스템 회색 배경, 예:
    /// #1C1C1E) 그대로 쓰면 대비가 1.13:1로 거의 안 보인다(공식 계산
    /// 확인). 이 변형은 같은 배경 위에서 대비 4.11:1이 나온다.
    /// `SettingsView.swift`의 복사 형식 미리보기 카드가 시스템이 다크 모드일
    /// 때만 이 값을 쓴다.
    static let navyOnDark = Color(hex: "#747D8F") ?? .indigo

    /// 와인 적갈 — [2026-09-04 신규] 차분한 적갈색.
    static let wine = Color(hex: "#7A3B42") ?? .pink

    /// 서가 슬레이트 — [2026-09-04 신규] 채도를 낮춘 청회색.
    static let shelfSlate = Color(hex: "#46586B") ?? .gray

    // [2026-09-11 신설] 연구문서 "문서함" 카드(DocumentsHomeView.swift)의
    // 책등 강조색 — 가죽 표지/와인 적갈/서가 슬레이트는 지금까지 밝은
    // 배경에서만 쓰여 "밤빛 서재"(#182644) 위에 그대로 칠하면 대비가
    // 부족하다(가죽 표지 원색 대비 약 2.1:1, 와인 적갈 약 2.4:1, 서가
    // 슬레이트 약 3.0:1 — 전부 UI 구성요소 권장 최소 3:1에 못 미치거나
    // 아슬아슬하다). `slateTealOnDark`/`navyOnDark`와 완전히 같은 방식
    // (흰색과 섞기)으로 밤빛 남색 대비 4.2:1 이상을 확인해 새로 만들었다 —
    // 이 대비 계산과 정확한 혼합 비율은 사용자에게 먼저 HTML 목업으로
    // 전달해 확인받았다(승인됨).

    /// 가죽 표지를 흰색과 40% 섞은 변형 — 밤빛 남색 대비 4.45:1.
    static let woodOnDark = Color(hex: "#9C887D") ?? .brown

    /// 와인 적갈을 흰색과 40% 섞은 변형 — 밤빛 남색 대비 4.85:1.
    static let wineOnDark = Color(hex: "#AF898E") ?? .pink

    /// 서가 슬레이트를 흰색과 30% 섞은 변형 — 밤빛 남색 대비 4.27:1.
    static let shelfSlateOnDark = Color(hex: "#7E8A97") ?? .gray
}
